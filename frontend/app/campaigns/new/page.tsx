"use client";

import { useEffect, useState } from "react";
import { useRouter } from "next/navigation";
import { Button } from "@/components/ui/button";
import { Card, CardContent, CardHeader, CardTitle } from "@/components/ui/card";
import { Input } from "@/components/ui/input";
import { Label } from "@/components/ui/label";
import { Textarea } from "@/components/ui/textarea";
import { OBJECTIVE_LABELS, generateCampaign } from "@/lib/generate";
import { getProfile } from "@/lib/store";
import { api, getToken, type CampaignOne } from "@/lib/auth";
import type { BusinessProfile, CampaignBrief, ContentLanguage, GeneratedCampaign, Objective, Platform } from "@/lib/types";

const PLATFORMS: Platform[] = ["Instagram", "Facebook", "WhatsApp", "Email"];
const LANGUAGES: ContentLanguage[] = ["English", "Hindi", "Hinglish"];
const BUDGET_PRESETS = [250, 750, 1500, 3000];

const PROGRESS = ["Understanding offer", "Writing content", "Preparing campaign"];

const selectClass =
  "h-9 w-full rounded-full border border-input bg-transparent px-4 text-sm outline-none focus-visible:border-ring focus-visible:ring-[3px] focus-visible:ring-ring/50";

export default function NewCampaign() {
  const router = useRouter();
  const [profile, setProfile] = useState<BusinessProfile | null | undefined>(undefined);
  const [form, setForm] = useState({
    objective: "offer" as Objective,
    offer: "",
    budget: 750,
    customBudget: "",
    startDate: "",
    durationDays: 7,
    platforms: ["Instagram", "WhatsApp"] as Platform[],
    tone: "",
    language: "English" as ContentLanguage,
  });
  const [step, setStep] = useState(-1); // -1 idle, 0..2 progress

  useEffect(() => {
    const p = getProfile();
    setProfile(p);
    if (!getToken()) router.replace("/login");
    else if (!p) router.replace("/onboarding");
    else setForm((f) => ({ ...f, tone: p.brandTone }));
  }, [router]);

  function togglePlatform(p: Platform) {
    setForm((f) => ({
      ...f,
      platforms: f.platforms.includes(p)
        ? f.platforms.filter((x) => x !== p)
        : [...f.platforms, p],
    }));
  }

  async function submit(e: React.FormEvent) {
    e.preventDefault();
    if (!profile || !form.platforms.length) return;
    const p = profile; // TS: narrowing does not reach the async callbacks below
    const budget = form.customBudget ? Number(form.customBudget) : form.budget;
    if (!budget || budget <= 0) return;
    const brief: CampaignBrief = {
      objective: form.objective,
      offer: form.offer,
      budget: Math.min(100000, Math.max(100, Math.round(budget))),
      startDate: form.startDate || undefined,
      durationDays: Math.min(30, Math.max(1, Number(form.durationDays) || 7)),
      platforms: form.platforms,
      tone: form.tone,
      language: form.language,
    };
    setStep(0);
    // AI backend first; local template generation is the fallback so the demo never dies.
    // No env needed: window hostname works for localhost AND LAN testers.
    const base = process.env.NEXT_PUBLIC_API_URL ?? `http://${window.location.hostname}:4000`;
    const ai = fetch(`${base}/api/campaigns/generate`, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ profile: p, brief }),
    })
      .then((r) => (r.ok ? r.json() : null))
      .catch(() => null);
    const t1 = setTimeout(() => setStep(1), 600);
    const t2 = setTimeout(() => setStep(2), 1200);
    const [aiResult] = await Promise.all([
      ai,
      new Promise((r) => setTimeout(r, 1800)),
    ]);
    clearTimeout(t1);
    clearTimeout(t2);
    const source: "ai" | "template" = aiResult?.campaign ? "ai" : "template";
    const generated: GeneratedCampaign =
      aiResult?.campaign ?? generateCampaign({ profile: p, brief });
    // store on the backend so the whole org can review it; source rides along so the
    // editor keeps its "generated by" badge
    try {
      const res = await api<CampaignOne>("/api/campaigns", {
        method: "POST",
        body: { profile: p, brief, generated: { ...generated, source } },
      });
      router.push(`/campaigns/${res.campaign.id}`);
    } catch (err) {
      if ((err as { status?: number }).status === 401) router.replace("/login");
      else {
        setStep(-1);
        alert("Could not save the campaign — is the backend running? Try again.");
      }
    }
  }

  // also covers null: useEffect redirects to /onboarding on first paint
  if (!profile) return <div className="p-8 text-sm text-muted-foreground">Loading…</div>;

  return (
    <div className="mx-auto max-w-2xl px-6 py-10 md:py-16">
      <p className="text-sm font-medium text-emerald-deep">Step 2 of 2 — Campaign brief</p>
      <h1 className="mt-2 text-3xl font-semibold tracking-tight md:text-4xl">
        What are we telling {profile.businessName}&rsquo;s customers?
      </h1>
      <p className="mt-2 text-sm text-muted-foreground">
        You&rsquo;ll get posts, a message, headlines, a poster, a budget plan, and a 7-day calendar.
      </p>

      <Card className="mt-8 rounded-card">
        <CardHeader>
          <CardTitle>Campaign brief</CardTitle>
        </CardHeader>
        <CardContent>
          <form onSubmit={submit} className="grid gap-5">
            <div className="grid gap-5 sm:grid-cols-2">
              <div className="grid gap-2">
                <Label htmlFor="objective">Marketing goal</Label>
                <select
                  id="objective"
                  className={selectClass}
                  value={form.objective}
                  onChange={(e) => setForm({ ...form, objective: e.target.value as Objective })}
                >
                  {Object.entries(OBJECTIVE_LABELS).map(([value, label]) => (
                    <option key={value} value={value}>
                      {label}
                    </option>
                  ))}
                </select>
              </div>
              <div className="grid gap-2">
                <Label htmlFor="durationDays">Duration (days)</Label>
                <Input
                  id="durationDays"
                  type="number"
                  min={1}
                  max={30}
                  value={form.durationDays}
                  onChange={(e) => setForm({ ...form, durationDays: Number(e.target.value) })}
                />
              </div>
            </div>
            <div className="grid gap-2">
              <Label htmlFor="offer">Offer or message</Label>
              <Textarea
                id="offer"
                required
                rows={3}
                value={form.offer}
                onChange={(e) => setForm({ ...form, offer: e.target.value })}
                placeholder="Weekday breakfast combo — coffee plus toastie before 11 a.m."
              />
            </div>
            <fieldset className="grid gap-2">
              <legend className="text-sm font-medium">Campaign budget (₹)</legend>
              <div className="flex flex-wrap gap-2">
                {BUDGET_PRESETS.map((b) => (
                  <button
                    key={b}
                    type="button"
                    aria-pressed={form.budget === b && !form.customBudget}
                    onClick={() => setForm({ ...form, budget: b, customBudget: "" })}
                    className={
                      "rounded-full border px-4 py-1.5 text-sm transition-colors duration-200 " +
                      (form.budget === b && !form.customBudget
                        ? "border-emerald-deep bg-emerald-deep text-paper"
                        : "border-border bg-card hover:border-emerald-deep")
                    }
                  >
                    ₹{b.toLocaleString("en-IN")}
                  </button>
                ))}
                <Input
                  aria-label="Custom budget"
                  type="number"
                  min={100}
                  placeholder="Custom"
                  className="w-28 rounded-full"
                  value={form.customBudget}
                  onChange={(e) => setForm({ ...form, customBudget: e.target.value })}
                />
              </div>
            </fieldset>
            <fieldset className="grid gap-2">
              <legend className="text-sm font-medium">Platforms</legend>
              <div className="flex flex-wrap gap-2">
                {PLATFORMS.map((p) => (
                  <label
                    key={p}
                    className="flex cursor-pointer items-center gap-2 rounded-full border border-border bg-card px-3 py-1.5 text-sm has-[input:checked]:border-emerald-deep has-[input:checked]:bg-emerald-deep has-[input:checked]:text-paper"
                  >
                    <input
                      type="checkbox"
                      className="accent-emerald-deep"
                      checked={form.platforms.includes(p)}
                      onChange={() => togglePlatform(p)}
                    />
                    {p}
                  </label>
                ))}
              </div>
              {!form.platforms.length && (
                <p className="text-xs text-destructive">Pick at least one platform.</p>
              )}
            </fieldset>
            <div className="grid gap-5 sm:grid-cols-3">
              <div className="grid gap-2">
                <Label htmlFor="startDate">Start date (optional)</Label>
                <Input
                  id="startDate"
                  type="date"
                  value={form.startDate}
                  onChange={(e) => setForm({ ...form, startDate: e.target.value })}
                />
              </div>
              <div className="grid gap-2">
                <Label htmlFor="tone">Tone</Label>
                <Input id="tone" required value={form.tone} onChange={(e) => setForm({ ...form, tone: e.target.value })} placeholder="Friendly" />
              </div>
              <div className="grid gap-2">
                <Label htmlFor="language">Content language</Label>
                <select id="language" className={selectClass} value={form.language} onChange={(e) => setForm({ ...form, language: e.target.value as ContentLanguage })}>
                  {LANGUAGES.map((l) => (
                    <option key={l}>{l}</option>
                  ))}
                </select>
              </div>
            </div>
            <Button
              type="submit"
              disabled={step >= 0 || !form.platforms.length}
              className="mt-2 w-full rounded-full sm:w-auto sm:justify-self-start sm:px-8"
            >
              {step >= 0 ? "Generating…" : "Generate campaign"}
            </Button>
          </form>
        </CardContent>
      </Card>

      {step >= 0 && (
        <ol className="mt-6 grid gap-2 text-sm" aria-label="Generation progress">
          {PROGRESS.map((label, i) => (
            <li key={label} className="flex items-center gap-3">
              <span
                aria-hidden
                className={
                  "size-2.5 rounded-full " +
                  (i < step ? "bg-emerald-deep" : i === step ? "bg-emerald shadow-[0_0_10px_rgba(32,229,154,0.8)]" : "bg-border")
                }
              />
              <span className={i <= step ? "text-foreground" : "text-muted-foreground"}>{label}</span>
              {i < step && <span className="text-xs text-muted-foreground">done</span>}
            </li>
          ))}
        </ol>
      )}
    </div>
  );
}
